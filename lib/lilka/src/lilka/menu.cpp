// Mono port: composite a 1bpp canvas onto any GFX target with color-key
// semantics. Pixels whose mono bit differs from the (thresholded) background
// are drawn; matching pixels are skipped, like the old transparent-color draw.
static void drawMonoCanvasTran(
    Arduino_GFX* g, lilka::Canvas* src, int16_t destX, int16_t destY, int16_t w, int16_t h, uint16_t bgColor
) {
    const bool bgBit = bgColor & 0b1000010000010000;
    const uint8_t* fb = src->getFramebuffer();
    const int16_t stride = src->monoStride();
    if (w > src->width()) w = src->width();
    if (h > src->height()) h = src->height();
    for (int16_t y = 0; y < h; y++) {
        const uint8_t* line = fb + y * stride;
        for (int16_t x = 0; x < w; x++) {
            const bool bit = line[x >> 3] & (0x80 >> (x & 7));
            if (bit != bgBit) {
                g->writePixel(destX + x, destY + y, bit ? 0xFFFF : 0x0000);
            }
        }
    }
}

// Composite a packed MonoIconAsset (1bpp color plane + 1bpp mask plane,
// generated by tools/image2code.py --mono) directly onto a GFX target.
// mask bit 0 = fully transparent, skip - real alpha-driven transparency,
// not a magic-color-key convention.
void drawMonoIcon(Arduino_GFX* g, const MonoIconAsset* icon, int16_t destX, int16_t destY) {
    const int16_t stride = (icon->width + 7) / 8;
    for (int16_t y = 0; y < icon->height; y++) {
        const uint8_t* colorLine = icon->color + y * stride;
        const uint8_t* maskLine = icon->mask + y * stride;
        for (int16_t x = 0; x < icon->width; x++) {
            const uint8_t bit = 0x80 >> (x & 7);
            if (!(maskLine[x >> 3] & bit)) continue; // transparent, skip
            const bool white = colorLine[x >> 3] & bit;
            g->writePixel(destX + x, destY + y, white ? 0xFFFF : 0x0000);
        }
    }
}

// Unpack a packed MonoIconAsset into an RGB565 lilka::Image buffer, for the
// ONE place that still genuinely needs RGB565: the cursor's rotating icon
// animation (drawSelectedIcon), which samples per-pixel through Transform/
// drawImageTransformed and can't operate on packed bits directly.
static void unpackIconToImage(const MonoIconAsset* icon, lilka::Image* dest, uint16_t transparentColor) {
    const int16_t w = icon->width < menu_icon_width ? icon->width : menu_icon_width;
    const int16_t h = icon->height < menu_icon_height ? icon->height : menu_icon_height;
    const int16_t stride = (icon->width + 7) / 8;
    for (int16_t y = 0; y < h; y++) {
        const uint8_t* colorLine = icon->color + y * stride;
        const uint8_t* maskLine = icon->mask + y * stride;
        for (int16_t x = 0; x < w; x++) {
            const uint8_t bit = 0x80 >> (x & 7);
            uint16_t px;
            if (!(maskLine[x >> 3] & bit)) {
                px = transparentColor;
            } else {
                px = (colorLine[x >> 3] & bit) ? lilka::colors::White : lilka::colors::Black;
            }
            dest->pixels[y * menu_icon_width + x] = px;
        }
    }
}



