void Menu::setCursor(int16_t cursor) {
    if (cursor < 0) {
        cursor = items.size() - 1;
    } else if (cursor >= items.size()) {
        cursor = 0;
    }
    this->cursor = cursor;
}

// List-mode cursor movement: UP/DOWN by 1 with wraparound, LEFT/RIGHT pages
// by MENU_HEIGHT. This is exactly the pre-grid update() logic, unchanged,
// just extracted so update() can dispatch to it.
void Menu::updateCursorList(State& state, bool& cursorMoved) {
    auto cursorLastPos = cursor;
    if (state.up.justPressed) {
        if (cursor == 0) {
            cursor = items.size() - 1;
        } else {
            cursor--;
        }
    } else if (state.down.justPressed) {
        cursor++;
        if (cursor >= items.size()) {
            cursor = 0;
        }
    } else if (state.left.justPressed) {
        if (cursor == 0) cursor = items.size() - 1;
        else cursor = (cursor - MENU_HEIGHT) <= 0 ? cursor = 0 : (cursor - MENU_HEIGHT);
    } else if (state.right.justPressed) {
        if (cursor == items.size() - 1) cursor = 0;
        else cursor = (cursor + MENU_HEIGHT) >= items.size() - 1 ? items.size() - 1 : (cursor + MENU_HEIGHT);
    }
    cursorMoved = (cursorLastPos != cursor);
    if (cursor < scroll) {
        scroll = cursor;
    } else if (cursor > scroll + MENU_HEIGHT - 1) {
        scroll = cursor - MENU_HEIGHT + 1;
    }
}

// Grid-mode cursor movement: UP/DOWN jump by gridColumns and wrap to the
// same column on the opposite edge row (clamped if the target row is
// shorter, e.g. a partially-filled last row). LEFT/RIGHT flow in reading
// order (right past the last column advances into the next row, rather
// than clamping at the row edge) - this also means a partially-filled last
// row needs no special-casing for LEFT/RIGHT.
void Menu::updateCursorGrid(State& state, bool& cursorMoved) {
    auto cursorLastPos = cursor;
    int16_t itemCount = items.size();
    if (itemCount == 0) {
        cursorMoved = false;
        return;
    }

    if (state.up.justPressed) {
        int16_t candidate = cursor - gridColumns;
        if (candidate < 0) {
            int16_t lastRowStart = (itemCount - 1) / gridColumns * gridColumns;
            candidate = lastRowStart + (cursor % gridColumns);
            if (candidate >= itemCount) candidate = itemCount - 1;
        }
        cursor = candidate;
    } else if (state.down.justPressed) {
        int16_t totalRows = (itemCount + gridColumns - 1) / gridColumns; // ceiling division
        int16_t cursorRow = cursor / gridColumns;
        int16_t candidate = cursor + gridColumns;
        if (cursorRow == totalRows - 1) {
            // truly on the last row (regardless of what's currently scrolled
            // into view) -> wrap to the top, same column
            cursor = cursor % gridColumns;
        } else if (candidate >= itemCount) {
            // not the last row, but the column below doesn't exist in a
            // ragged final row -> clamp to the last real item
            cursor = itemCount - 1;
        } else {
            cursor = candidate;
        }
    } else if (state.left.justPressed) {
        cursor = (cursor == 0) ? itemCount - 1 : cursor - 1;
    } else if (state.right.justPressed) {
        cursor = (cursor == itemCount - 1) ? 0 : cursor + 1;
    }
    cursorMoved = (cursorLastPos != cursor);

    int16_t cursorRow = cursor / gridColumns;
    int16_t scrollRow = scroll / gridColumns;
    if (cursorRow < scrollRow) {
        scroll = cursorRow * gridColumns;
    } else if (cursorRow > scrollRow + gridVisibleRows - 1) {
        scroll = (cursorRow - gridVisibleRows + 1) * gridColumns;
    }
}

void Menu::update() {
    State state = controller.getState();
    bool cursorMoved = false;

    if (layout == MenuLayout::GRID) {
        updateCursorGrid(state, cursorMoved);
    } else {
        updateCursorList(state, cursorMoved);
    }
    if (cursorMoved) lastCursorMoveUs = micros();

    for (Button activationButton : activationButtons) {
        lilka::_StateButtons& buttonsArray = *reinterpret_cast<lilka::_StateButtons*>(&state);
        if (buttonsArray[activationButton].justPressed) {
            button = activationButton;
            done = true;
            // Should be made after done flag setup to allow to clear it by isFinished() call
            if (items[cursor].callback) { // call callback if
                items[cursor].callback(items[cursor].callbackData);
            }
        }
    }
    vTaskDelay(LILKA_UI_UPDATE_DELAY_MS / portTICK_PERIOD_MS);
}

// Scroll marquee back and forth based on time, pausing at start and end
int16_t calculateMarqueeShift(uint64_t time, uint16_t maxShift, uint16_t pixelsPerSecond) {
    constexpr uint64_t startDelay = 750;
    uint64_t midTime = maxShift * 1000 / pixelsPerSecond;
    constexpr uint64_t endDelay = 750;
    const uint64_t period = startDelay + 2 * midTime + endDelay;
    const uint64_t phase = time % period;

    int16_t shift = 0;
    if (phase < startDelay) {
        // Start delay
        shift = 0;
    } else if (phase < startDelay + midTime) {
        // Scroll
        shift = (phase - startDelay) * pixelsPerSecond / 1000;
    } else if (phase < startDelay + midTime + endDelay) {
        // End delay
        shift = maxShift;
    } else {
        // Scroll back
        shift = maxShift - (phase - startDelay - midTime - endDelay) * pixelsPerSecond / 1000;
    }
    return -shift;
}

// Shared by drawList and drawGrid: draws the cursor's icon inverted, with
// the rotation-wobble animation, at an arbitrary destination point.
void Menu::drawSelectedIcon(Arduino_GFX* canvas, const menu_icon_t* icon, int16_t destX, int16_t destY) {
    // Unpack inverted (transparent pixels become white bg, opaque pixels
    // swap black<->white) so the selected icon reads correctly against the
    // highlight background - real alpha-aware inversion, replaces the old
    // raw-byte-invert trick that only worked because RGB565 0x0000/0xFFFF
    // happened to bit-invert cleanly.
    for (int16_t y = 0; y < menu_icon_height; y++) {
        const int16_t stride = (icon->width + 7) / 8;
        const uint8_t* colorLine = icon->color + y * stride;
        const uint8_t* maskLine = icon->mask + y * stride;
        for (int16_t x = 0; x < menu_icon_width; x++) {
            const uint8_t bit = 0x80 >> (x & 7);
            bool opaque = maskLine[x >> 3] & bit;
            bool whiteInSource = colorLine[x >> 3] & bit;
            iconImage->pixels[y * menu_icon_width + x] =
                (opaque && !whiteInSource) ? lilka::colors::White : lilka::colors::Black;
        }
    }

    // add rotation animation to icon
    // float elapsedMs = (micros() - lastCursorMoveUs) * 0.001f;
    // Transform t = Transform().rotate(sinf(elapsedMs * PI / 1000.0f) * 3.0f);
    // iconCanvas->fillScreen(lilka::colors::White);
    // iconCanvas->drawImageTransformed(iconImage, 12, 12, t);
    // drawMonoCanvasTran(canvas, iconCanvas, destX, destY, menu_icon_width, menu_icon_height, lilka::colors::White); // should be black??!
    float elapsedMs = (micros() - lastCursorMoveUs) * 0.001f;
    Transform t = Transform().rotate(sinf(elapsedMs * PI / 1000.0f) * 3.0f);
    t.scale(1.1, 1.1);
    iconCanvas->fillScreen(lilka::colors::Black);
    iconCanvas->drawImageTransformed(iconImage, 12, 12, t);
    // iconCanvas->drawImage(iconImage, 12, 12);
    drawMonoCanvasTran(canvas, iconCanvas, destX, destY, menu_icon_width, menu_icon_height, lilka::colors::Black);
    
}

void Menu::draw(Arduino_GFX* canvas) {
    if (layout == MenuLayout::GRID) {
        drawGrid(canvas);
    } else {
        drawList(canvas);
    }
}

